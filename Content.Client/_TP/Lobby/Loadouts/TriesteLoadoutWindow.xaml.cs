namespace Content.Client._TP.Lobby.Loadouts;

/// <summary>
///     Fork of <see cref="LoadoutWindow"/> that can nest loadout groups under <see cref="TriesteLoadoutCategoryPrototype"/> tabs. 
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class TriesteLoadoutWindow : FancyWindow
{
    public event Action<string>? OnNameChanged;
    public event Action<ProtoId<LoadoutGroupPrototype>, ProtoId<LoadoutPrototype>>? OnLoadoutPressed;
    public event Action<ProtoId<LoadoutGroupPrototype>, ProtoId<LoadoutPrototype>>? OnLoadoutUnpressed;

    private readonly List<LoadoutGroupContainer> _groups = new();

    public HumanoidCharacterProfile Profile;

    private readonly int _maxLoadoutNameLength;

    public TriesteLoadoutWindow(HumanoidCharacterProfile profile, RoleLoadout loadout, RoleLoadoutPrototype proto, ICommonSession session, IDependencyCollection collection)
    {
        RobustXamlLoader.Load(this);
        Profile = profile;
        var protoManager = collection.Resolve<IPrototypeManager>();
        var configManager = collection.Resolve<IConfigurationManager>();

        _maxLoadoutNameLength = configManager.GetCVar(CCVars.MaxLoadoutNameLength);
        RoleNameEdit.IsValid = text => text.Length <= _maxLoadoutNameLength;

        // Hide it if we can't edit the name.
        if (!proto.CanCustomizeName)
        {
            RoleNameBox.Visible = false;
        }
        else
        {
            var name = loadout.EntityName;

            LoadoutNameLabel.Text = proto.NameDataset == null ?
                Loc.GetString("loadout-name-edit-label") :
                Loc.GetString("loadout-name-edit-label-dataset");

            RoleNameEdit.ToolTip = Loc.GetString(
                "loadout-name-edit-tooltip",
                ("max", _maxLoadoutNameLength));
            RoleNameEdit.Text = name ?? string.Empty;
            RoleNameEdit.OnTextChanged += args => OnNameChanged?.Invoke(args.Text);
        }

        // Hide the groups if there are none.
        if (proto.Groups.Count == 0)
        {
            LoadoutGroupsContainer.Visible = false;
            SetSize = Vector2.Zero;
            return;
        }

        BuildTabs(profile, loadout, proto, session, collection, protoManager);
    }

    private void BuildTabs(
        HumanoidCharacterProfile profile,
        RoleLoadout loadout,
        RoleLoadoutPrototype proto,
        ICommonSession session,
        IDependencyCollection collection,
        IPrototypeManager protoManager)
    {
        // Group to category lookup.
        var categoryOf = new Dictionary<ProtoId<LoadoutGroupPrototype>, TriesteLoadoutCategoryPrototype>();
        foreach (var category in protoManager.EnumeratePrototypes<TriesteLoadoutCategoryPrototype>())
        {
            foreach (var group in category.Groups)
            {
                categoryOf.TryAdd(group, category);
            }
        }

        // Visible groups for this role, in the role's order.
        var visible = new List<LoadoutGroupPrototype>();
        var categoryCounts = new Dictionary<string, int>();
        foreach (var group in proto.Groups)
        {
            if (!protoManager.Resolve(group, out var groupProto) || groupProto.Hidden)
                continue;

            visible.Add(groupProto);

            if (categoryOf.TryGetValue(group, out var category))
                categoryCounts[category.ID] = categoryCounts.GetValueOrDefault(category.ID) + 1;
        }

        // Now we place the category tabs where their first member group is.
        var categoryTabs = new Dictionary<string, TabContainer>();
        foreach (var groupProto in visible)
        {
            var container = CreateGroupContainer(profile, loadout, groupProto, session, collection);
            var groupTitle = Loc.GetString(groupProto.Name);

            if (!categoryOf.TryGetValue(groupProto.ID, out var category)
                || category.CollapseSingle && categoryCounts[category.ID] <= 1)
            {
                LoadoutGroupsContainer.AddTab(container, groupTitle);
                continue;
            }

            if (!categoryTabs.TryGetValue(category.ID, out var tabs))
            {
                tabs = new TabContainer
                {
                    HorizontalExpand = true,
                    VerticalExpand = true,
                };
                categoryTabs[category.ID] = tabs;
                LoadoutGroupsContainer.AddTab(tabs, Loc.GetString(category.Name));
            }

            tabs.AddChild(container);
            tabs.SetTabTitle(tabs.ChildCount - 1, groupTitle);
        }
    }

    private LoadoutGroupContainer CreateGroupContainer(
        HumanoidCharacterProfile profile,
        RoleLoadout loadout,
        LoadoutGroupPrototype groupProto,
        ICommonSession session,
        IDependencyCollection collection)
    {
        ProtoId<LoadoutGroupPrototype> group = groupProto.ID;
        var container = new LoadoutGroupContainer(profile, loadout, groupProto, session, collection);
        _groups.Add(container);

        container.OnLoadoutPressed += args =>
        {
            OnLoadoutPressed?.Invoke(group, args);
        };

        container.OnLoadoutUnpressed += args =>
        {
            OnLoadoutUnpressed?.Invoke(group, args);
        };

        return container;
    }

    public void RefreshLoadouts(RoleLoadout loadout, ICommonSession session, IDependencyCollection collection)
    {
        foreach (var group in _groups)
        {
            group.RefreshLoadouts(Profile, loadout, session, collection);
        }
    }
}
