using Content.Client.UserInterface.Controls;
using Content.Shared._TP.Research.Planktology;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._TP.Research.Planktology.UI;

[GenerateTypedNameReferences]
public sealed partial class PlanktonSeparatorWindow : FancyWindow
{
    public event Action? OnDeposit;
    public event Action<PlanktonSeparatorEntry>? OnExtract;

    public PlanktonSeparatorWindow()
    {
        RobustXamlLoader.Load(this);

        DepositButton.OnPressed += _ => OnDeposit?.Invoke();
    }

    public void UpdateState(PlanktonSeparatorBoundUserInterfaceState state)
    {
        ContainerLabel.Text = state.HasContainer
            ? Loc.GetString("plankton-separator-container", ("count", state.ContainerSpeciesCount))
            : Loc.GetString("plankton-separator-no-container");

        DepositButton.Disabled = !state.HasContainer || state.ContainerSpeciesCount == 0;

        SpeciesList.RemoveAllChildren();

        if (state.Frozen.Count == 0)
        {
            SpeciesList.AddChild(new Label
            {
                Text = Loc.GetString("plankton-separator-empty"),
                FontColorOverride = Color.Gray,
            });
            return;
        }

        foreach (var entry in state.Frozen)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };

            row.AddChild(new Label
            {
                Text = Loc.GetString("plankton-separator-entry",
                    ("name", entry.Name),
                    ("alive", entry.Alive),
                    ("size", (int) MathF.Round(entry.Size))),
                HorizontalExpand = true,
                ClipText = true,
            });

            var extract = new Button
            {
                Text = Loc.GetString("plankton-separator-extract"),
                Disabled = !state.HasContainer,
            };
            extract.OnPressed += _ => OnExtract?.Invoke(entry);
            row.AddChild(extract);

            SpeciesList.AddChild(row);
        }
    }
}
