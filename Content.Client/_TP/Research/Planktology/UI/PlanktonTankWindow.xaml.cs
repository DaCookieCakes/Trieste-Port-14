using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._TP.Research.Planktology;
using Content.Shared._TP.Research.Planktology.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._TP.Research.Planktology.UI;

[GenerateTypedNameReferences]
public sealed partial class PlanktonTankWindow : FancyWindow
{
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    private const string EmptyField = "________________";

    public event Action<int>? OnInject;
    public event Action? OnDump;
    public event Action? OnExtract;
    public event Action? OnToggleLights;
    public event Action<bool>? OnAdjustTemperature;
    public event Action? OnRadiationFlash;

    public event Action<int, int, ProtoId<PlanktonDietPrototype>>? OnGuessDiet;
    public event Action<int, int, ProtoId<PlanktonCharacteristicPrototype>>? OnGuessCharacteristic;
    public event Action<int, int, string>? OnCrossOut;
    public event Action<int, int>? OnSubmit;

    private PlanktonTankBoundUserInterfaceState? _state;

    /// <summary>
    ///     The number of the selected colony, kept by number so the selection survives colonies moving around.
    /// </summary>
    private int? _selectedNumber;

    private bool _showingDiets;

    public PlanktonTankWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Inject5Button.OnPressed += _ => OnInject?.Invoke(5);
        Inject10Button.OnPressed += _ => OnInject?.Invoke(10);
        DumpButton.OnPressed += _ => OnDump?.Invoke();
        ExtractButton.OnPressed += _ => OnExtract?.Invoke();
        LightsButton.OnPressed += _ => OnToggleLights?.Invoke();
        CoolButton.OnPressed += _ => OnAdjustTemperature?.Invoke(false);
        HeatButton.OnPressed += _ => OnAdjustTemperature?.Invoke(true);
        RadiationButton.OnPressed += _ => OnRadiationFlash?.Invoke();

        TankView.OnSpeciesClicked += index =>
        {
            if (_state == null || index >= _state.Species.Count)
                return;

            _selectedNumber = _state.Species[index].Number;
            Refresh();
        };

        DietField.OnPressed += _ =>
        {
            _showingDiets = true;
            Refresh();
        };

        CharacteristicsField.OnPressed += _ =>
        {
            _showingDiets = false;
            Refresh();
        };

        SubmitButton.OnPressed += _ =>
        {
            if (GetSelected() is { } selected)
                OnSubmit?.Invoke(selected.Index, selected.Species.Number);
        };
    }

    public void UpdateState(PlanktonTankBoundUserInterfaceState state)
    {
        _state = state;
        TankView.UpdateState(state);
        Refresh();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateRadiationButton();
    }

    private (int Index, PlanktonSpecies Species)? GetSelected()
    {
        if (_state == null || _state.Species.Count == 0)
            return null;

        var index = _state.Species.FindIndex(s => s.Number == _selectedNumber);
        if (index < 0)
        {
            index = 0;
            _selectedNumber = _state.Species[0].Number;
        }

        return (index, _state.Species[index]);
    }

    private void Refresh()
    {
        if (_state == null)
            return;

        var state = _state;

        // Beaker readout
        BeakerLabel.Text = state.BeakerName ?? Loc.GetString("plankton-tank-ui-no-beaker");
        BeakerBar.Value = state.BeakerMaxVolume > 0 ? (state.BeakerVolume / state.BeakerMaxVolume).Float() : 0f;
        Inject5Button.Disabled = state.BeakerName == null;
        Inject10Button.Disabled = state.BeakerName == null;
        TankVolumeLabel.Text = Loc.GetString("plankton-tank-ui-tank-volume",
            ("volume", state.TankVolume.Int()),
            ("max", state.TankMaxVolume.Int()));

        // Container
        ContainerLabel.Text = state.HasContainer
            ? Loc.GetString("plankton-tank-ui-container-count", ("count", state.ContainerSpeciesCount))
            : Loc.GetString("plankton-tank-ui-no-container");
        DumpButton.Disabled = !state.HasContainer
            || state.ContainerSpeciesCount == 0
            || state.Species.Count + state.ContainerSpeciesCount > state.MaxSpecies;
        ExtractButton.Disabled = !state.HasContainer || state.Species.Count == 0;

        // Controls
        LightsButton.Pressed = state.LightsOn;
        LightsButton.Disabled = !state.Powered;
        CoolButton.Disabled = !state.Powered || state.Temperature <= state.MinTemperature;
        HeatButton.Disabled = !state.Powered || state.Temperature >= state.MaxTemperature;
        TemperatureLabel.Text = Loc.GetString("plankton-tank-ui-temperature",
            ("temperature", (int) MathF.Round(state.Temperature - 273.15f)));
        PowerLabel.Text = state.Powered ? string.Empty : Loc.GetString("plankton-tank-ui-unpowered");
        UpdateRadiationButton();

        // Form
        var selected = GetSelected();
        TankView.Selected = selected?.Index;
        UpdateForm(selected);
    }

    private void UpdateRadiationButton()
    {
        if (_state == null)
            return;

        var remaining = _state.NextRadiationFlash - _timing.CurTime;
        if (remaining > TimeSpan.Zero)
        {
            RadiationButton.Text = Loc.GetString("plankton-tank-ui-radiation-cooldown",
                ("seconds", (int) Math.Ceiling(remaining.TotalSeconds)));
            RadiationButton.Disabled = true;
        }
        else
        {
            RadiationButton.Text = Loc.GetString("plankton-tank-ui-radiation");
            RadiationButton.Disabled = !_state.Powered;
        }
    }

    private void UpdateForm((int Index, PlanktonSpecies Species)? selected)
    {
        OptionList.RemoveAllChildren();

        if (selected is not { } sel)
        {
            FormNameLabel.Text = Loc.GetString("plankton-tank-ui-form-empty");
            FormStatusLabel.Text = string.Empty;
            DietField.Text = EmptyField;
            CharacteristicsField.Text = EmptyField;
            DietField.Disabled = true;
            CharacteristicsField.Disabled = true;
            SubmitButton.Disabled = true;
            ListHeader.Text = string.Empty;
            return;
        }

        var (index, species) = sel;
        var locked = species.Submitted;

        FormNameLabel.Text = Loc.GetString("plankton-tank-ui-form-name", ("number", species.Number), ("name", species.Name));
        FormStatusLabel.Text = GetStatus(species);

        DietField.Disabled = false;
        CharacteristicsField.Disabled = false;
        DietField.Text = species.GuessedDiet is { } guessedDiet ? Loc.GetString(_proto.Index(guessedDiet).Name) : EmptyField;
        CharacteristicsField.Text = species.GuessedCharacteristics.Count > 0
            ? string.Join(", ", species.GuessedCharacteristics.Select(c => Loc.GetString(_proto.Index(c).Name)))
            : EmptyField;

        SubmitButton.Disabled = locked
            || !species.Alive
            || species.Size < _state!.MinimumSubmitSize
            || species.GuessedDiet == null
            || !_state.HasServer;

        if (_showingDiets)
        {
            ListHeader.Text = Loc.GetString("plankton-tank-ui-diet-list");
            foreach (var diet in _proto.EnumeratePrototypes<PlanktonDietPrototype>().OrderBy(d => Loc.GetString(d.Name)))
            {
                AddOption(diet.ID,
                    Loc.GetString(diet.Name),
                    species.GuessedDiet == diet.ID,
                    species,
                    locked,
                    () => OnGuessDiet?.Invoke(index, species.Number, diet.ID));
            }
        }
        else
        {
            ListHeader.Text = Loc.GetString("plankton-tank-ui-characteristic-list",
                ("count", species.GuessedCharacteristics.Count));
            foreach (var characteristic in _proto.EnumeratePrototypes<PlanktonCharacteristicPrototype>().OrderBy(c => Loc.GetString(c.Name)))
            {
                var picked = species.GuessedCharacteristics.Contains(characteristic.ID);
                AddOption(characteristic.ID,
                    Loc.GetString(characteristic.Name),
                    picked,
                    species,
                    // The form only has three lines, so unpicked entries lock once it's full.
                    locked || !picked && species.GuessedCharacteristics.Count >= 3,
                    () => OnGuessCharacteristic?.Invoke(index, species.Number, characteristic.ID));
            }
        }
    }

    private string GetStatus(PlanktonSpecies species)
    {
        if (species.Submitted)
        {
            return Loc.GetString(species.SubmittedCorrect
                ? "plankton-tank-ui-status-correct"
                : "plankton-tank-ui-status-incorrect");
        }

        if (!species.Alive)
            return Loc.GetString("plankton-tank-ui-status-dead");

        if (species.Size < _state!.MinimumSubmitSize)
            return Loc.GetString("plankton-tank-ui-status-small");

        if (!_state.HasServer)
            return Loc.GetString("plankton-tank-ui-status-no-server");

        return Loc.GetString("plankton-tank-ui-status-ready");
    }

    /// <summary>
    ///     One entry in the right-hand list: a pick button and a cross-out button.
    /// </summary>
    private void AddOption(string id, string name, bool picked, PlanktonSpecies species, bool locked, Action onPick)
    {
        var crossed = species.CrossedOut.Contains(id);
        var mark = picked ? "[x]" : crossed ? "[-]" : "[-]";

        var pick = new Button
        {
            Text = $"{mark} {name}",
            HorizontalExpand = true,
            ClipText = true,
            Disabled = locked && !picked || species.Submitted,
            StyleClasses = { "OpenRight" },
        };
        if (crossed)
            pick.Label.FontColorOverride = Color.DimGray;
        pick.OnPressed += _ => onPick();

        var cross = new Button
        {
            Text = "X",
            ToolTip = Loc.GetString("plankton-tank-ui-cross-out"),
            Disabled = species.Submitted,
            Pressed = crossed,
            ToggleMode = true,
            StyleClasses = { "OpenLeft" },
        };
        var index = _state!.Species.IndexOf(species);
        cross.OnPressed += _ => OnCrossOut?.Invoke(index, species.Number, id);

        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
        row.AddChild(pick);
        row.AddChild(cross);
        OptionList.AddChild(row);
    }
}
